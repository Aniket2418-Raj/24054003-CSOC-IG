import numpy as np
import matplotlib.pyplot as plt

# Environment Creation
class CliffWalkingEnv:
    """
    A custom implementation of the classic Cliff Walking environment
    as described in Sutton & Barto's Reinforcement Learning book.
    """

    def __init__(self, rows=4, cols=12):
        self.rows = rows
        self.cols = cols
        self.start = (rows - 1, 0)              # Start in bottom-left corner
        self.goal = (rows - 1, cols - 1)        # Goal in bottom-right corner
        self.cliff = [(rows - 1, i) for i in range(1, cols - 1)]  # Dangerous cliff area
        self.action_space = [0, 1, 2, 3]        # 0: Up, 1: Down, 2: Left, 3: Right
        self.state = self.start

    def reset(self):
        self.state = self.start
        return self._to_state(self.state)

    def step(self, action):
        r, c = self.state

        # Move agent according to action
        if action == 0: r = max(r - 1, 0)  # Up
        elif action == 1: r = min(r + 1, self.rows - 1)  # Down
        elif action == 2: c = max(c - 1, 0)  # Left
        elif action == 3: c = min(c + 1, self.cols - 1)  # Right

        new_state = (r, c)

        # Check for cliff fall
        if new_state in self.cliff:
            reward = -100
            new_state = self.start
            done = False
        elif new_state == self.goal:
            reward = 0
            done = True
        else:
            reward = -1
            done = False

        self.state = new_state
        return self._to_state(new_state), reward, done

    def _to_state(self, pos):
        """Convert (row, col) to integer state index"""
        return pos[0] * self.cols + pos[1]

    def get_pos(self, state):
        """Convert integer state back to (row, col)"""
        return (state // self.cols, state % self.cols)

# Epsilon-Greedy Policy
def epsilon_greedy(Q, state, epsilon, n_actions):
    if np.random.rand() < epsilon:
        return np.random.choice(n_actions)  # Explore
    return np.argmax(Q[state])              # Exploit

# Q-Learning Agent
def q_learning(env, episodes, alpha, gamma, epsilon):
    Q = np.zeros((env.rows * env.cols, 4))
    rewards = []

    for ep in range(episodes):
        state = env.reset()
        total_reward = 0
        done = False

        while not done:
            action = epsilon_greedy(Q, state, epsilon, 4)
            next_state, reward, done = env.step(action)

            # Q-Learning Update (off-policy)
            best_next = np.argmax(Q[next_state])
            Q[state][action] += alpha * (reward + gamma * Q[next_state][best_next] - Q[state][action])

            state = next_state
            total_reward += reward

        rewards.append(total_reward)
    return Q, rewards

# SARSA Agent
def sarsa(env, episodes, alpha, gamma, epsilon):
    Q = np.zeros((env.rows * env.cols, 4))
    rewards = []

    for ep in range(episodes):
        state = env.reset()
        action = epsilon_greedy(Q, state, epsilon, 4)
        total_reward = 0
        done = False

        while not done:
            next_state, reward, done = env.step(action)
            next_action = epsilon_greedy(Q, next_state, epsilon, 4)

            # SARSA Update (on-policy)
            Q[state][action] += alpha * (reward + gamma * Q[next_state][next_action] - Q[state][action])

            state = next_state
            action = next_action
            total_reward += reward

        rewards.append(total_reward)
    return Q, rewards

# Reward Plotting
def plot_rewards(q_rewards, sarsa_rewards):
    plt.figure(figsize=(12, 6))
    plt.plot(q_rewards, label='Q-Learning (Off-policy)', color='royalblue')
    plt.plot(sarsa_rewards, label='SARSA (On-policy)', color='orange')
    plt.xlabel('Episodes')
    plt.ylabel('Total Reward')
    plt.title('Cliff Walking: Q-Learning vs SARSA Performance')
    plt.legend()
    plt.grid(True)
    plt.tight_layout()
    plt.show()

